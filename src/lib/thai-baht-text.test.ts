import { describe, it, expect } from "vitest";
import { toThaiBahtText } from "./thai-baht-text";

describe("toThaiBahtText — เทียบกับตัวอย่างเอกสารจริงที่ผู้ใช้ส่งมา", () => {
  it("88,410.00 -> แปดหมื่นแปดพันสี่ร้อยสิบบาทถ้วน (ตรงกับใบส่งของชั่วคราวตัวอย่างจริง)", () => {
    expect(toThaiBahtText(88410)).toBe("แปดหมื่นแปดพันสี่ร้อยสิบบาทถ้วน");
  });

  it("348,250.00 -> สามแสนสี่หมื่นแปดพันสองร้อยห้าสิบบาทถ้วน (ตรงกับใบวางบิลตัวอย่างจริง)", () => {
    expect(toThaiBahtText(348250)).toBe("สามแสนสี่หมื่นแปดพันสองร้อยห้าสิบบาทถ้วน");
  });

  it("25,174.96 -> สองหมื่นห้าพันหนึ่งร้อยเจ็ดสิบสี่บาทเก้าสิบหกสตางค์ (ตรงกับใบกำกับภาษีตัวอย่างจริง)", () => {
    expect(toThaiBahtText(25174.96)).toBe("สองหมื่นห้าพันหนึ่งร้อยเจ็ดสิบสี่บาทเก้าสิบหกสตางค์");
  });

  it("จัดการ เอ็ด/ยี่สิบ ให้ถูกต้อง", () => {
    expect(toThaiBahtText(1)).toBe("หนึ่งบาทถ้วน");
    expect(toThaiBahtText(11)).toBe("สิบเอ็ดบาทถ้วน");
    expect(toThaiBahtText(21)).toBe("ยี่สิบเอ็ดบาทถ้วน");
    expect(toThaiBahtText(100)).toBe("หนึ่งร้อยบาทถ้วน");
    expect(toThaiBahtText(0)).toBe("ศูนย์บาทถ้วน");
  });

  it("จัดการหลักล้านได้", () => {
    expect(toThaiBahtText(1000000)).toBe("หนึ่งล้านบาทถ้วน");
    expect(toThaiBahtText(2500000)).toBe("สองล้านห้าแสนบาทถ้วน");
  });
});
