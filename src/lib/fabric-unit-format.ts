// หน่วยให้เอง — กติกาการเติม: "g" (น้ำหนักใย) ติดกับตัวเลขเลย ไม่เว้นวรรค, "mm" (ความหนาฟองน้ำ)
// เว้น 1 ช่องเหมือนเดิม (ตรงกับที่ข้อมูลจริงส่วนใหญ่ในระบบเขียนอยู่แล้ว)
//
// ค่าที่เก็บใน DB ยังเป็น string เต็มรูปแบบเหมือนเดิมทุกประการ (ไม่แตะ schema/ไม่ migrate
// ข้อมูลเก่า) — ฟังก์ชันนี้แค่ช่วยฟอร์ม: strip หน่วยออกตอนโหลดมาแก้ (โชว์แค่ตัวเลขในช่อง)
// แล้ว format ใส่หน่วยกลับก่อน submit เท่านั้น

/** ดึงเฉพาะตัวเลขนำหน้า (รองรับทศนิยม) ออกจากค่าที่อาจมีหน่วยติดมาแล้ว (เช่น "280g" ->
 * "280", "10 mm" -> "10", "15mm" -> "15") — ค่าที่พิมพ์แค่ตัวเลขอยู่แล้วก็ผ่านตรงๆ ไม่เปลี่ยน */
export function stripUnitToNumber(raw: string): string {
  const match = raw.trim().match(/^(\d+(?:\.\d+)?)/);
  return match ? match[1] : raw.trim();
}

/** เติมหน่วย "g" ติดตัวเลขทันที ไม่เว้นวรรค — คืนค่าว่างถ้าไม่มีตัวเลข */
export function formatWaddingWeight(numeric: string): string {
  const n = numeric.trim();
  return n ? `${n}g` : "";
}

/** เติมหน่วย "mm" เว้น 1 ช่องจากตัวเลข — คืนค่าว่างถ้าไม่มีตัวเลข */
export function formatFoamThickness(numeric: string): string {
  const n = numeric.trim();
  return n ? `${n} mm` : "";
}
